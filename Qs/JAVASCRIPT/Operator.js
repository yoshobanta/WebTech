var a = 10;
var b = 20;

// Addition
var add = a + b;
console.log("Addition: " + add);

// Subtraction
var subtract = a - b;
console.log("Subtraction: " + subtract);

// Multiplication
var multiply = a * b;
console.log("Multiplication: " + multiply);

// Division
var divide = a / b;
console.log("Division: " + divide);

// Modulus (remainder)
var modulus = a % b;
console.log("Modulus: " + modulus);

// Exponentiation (a raised to the power b)
var exponent = a ** 2;
console.log("Exponentiation (a^2): " + exponent);

// Increment
a++;
console.log("Increment a: " + a);

// Decrement
b--;
console.log("Decrement b: " + b);

